// The portable's splash (D-216, D-218): shown by the portable's launcher from the double-click until
// the app's window is on screen. A card with the window's corner radius (radius.window), the app's
// icon, its name, and one quiet line saying what's happening (Starting, Unpacking with a percentage,
// Opening your notes). Paper's tokens: canvas, border, text and textMuted.
// Writes build/portable-splash.bmp (the 24-bit bitmap the launcher shows) and build/portable-splash.nsh
// (the launcher's part: the rounded window, the words and the waits; loaded by the patched portable.nsi).
// Run: node scripts/portable-splash.mjs (or --check, which fails if either file differs).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { render } from "./icon.mjs";

const SPLASH = {
  width: 360, height: 264, radius: 20,
  icon: { size: 96, top: 44 },
  title: { text: "Focus Notes", top: 152, height: 28, font: "Segoe UI", pt: 15, weight: 600 },
  status: { top: 188, height: 22, font: "Segoe UI", pt: 10, weight: 400 },
  color: { canvas: "#fbfaf7", border: "#e9e6de", text: "#1f1d1a", textMuted: "#5f5a52" },
  words: { starting: "Starting…", unpacking: "Unpacking the app…", opening: "Opening your notes…" },
  // How long the splash waits for the app's window before stepping aside (100 ms steps).
  waitSteps: 300,
};

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const mix = (a, b, t) => a.map((v, i) => Math.round(v * (1 - t) + b[i] * t));

/** Signed distance from a pixel's center to the card's rounded edge (negative inside). */
function edge(x, y) {
  const { width: w, height: h, radius: r } = SPLASH;
  const qx = Math.abs(x + 0.5 - w / 2) - (w / 2 - r), qy = Math.abs(y + 0.5 - h / 2) - (h / 2 - r);
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r;
}

function bitmap() {
  const { width: w, height: h, icon: { size: s, top } } = SPLASH;
  const icon = render(s);
  const bg = rgb(SPLASH.color.canvas), line = rgb(SPLASH.color.border);
  const x0 = Math.round((w - s) / 2);
  const row = Math.ceil((w * 3) / 4) * 4;
  const pixels = Buffer.alloc(row * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    // A 1 px border along the curve; past it (where the window's region still keeps a pixel) the
    // border's color, so the region's stepped edge reads as part of the line.
    const d = edge(x, y);
    let c = d > 0 ? line : mix(bg, line, Math.max(0, Math.min(1, Math.min(d + 1, -d) + 0.5)));
    const ix = x - x0, iy = y - top;
    if (ix >= 0 && iy >= 0 && ix < s && iy < s) {
      const o = (iy * s + ix) * 4, a = icon[o + 3] / 255;
      c = c.map((v, i) => Math.round(icon[o + i] * a + v * (1 - a)));
    }
    // Bottom-up rows, blue-green-red.
    const p = (h - 1 - y) * row + x * 3;
    pixels[p] = c[2]; pixels[p + 1] = c[1]; pixels[p + 2] = c[0];
  }
  const head = Buffer.alloc(54);
  head.write("BM", 0, "ascii");
  head.writeUInt32LE(54 + pixels.length, 2);
  head.writeUInt32LE(54, 10);
  head.writeUInt32LE(40, 14);
  head.writeInt32LE(w, 18);
  head.writeInt32LE(h, 22);
  head.writeUInt16LE(1, 26);
  head.writeUInt16LE(24, 28);
  head.writeUInt32LE(pixels.length, 34);
  head.writeInt32LE(2835, 38);
  head.writeInt32LE(2835, 42);
  return Buffer.concat([head, pixels]);
}

function script() {
  const { width: w, height: h, radius: r, title: t, status: st, words, waitSteps } = SPLASH;
  const text = rgb(SPLASH.color.text).join(" "), muted = rgb(SPLASH.color.textMuted).join(" ");
  const lines = [
    "; Generated by apps/desktop/scripts/portable-splash.mjs (D-218). Don't edit; run the script.",
    "; Loaded by the portable launcher (patches/app-builder-lib@26.15.3.patch) when splashImage is set.",
    "",
    "Var splashTitleFont",
    "Var splashStatusFont",
    "Var splashPercent",
    "Var splashText",
    "Var splashX",
    "Var splashSize",
    "Var splashDc",
    "Var splashOldFont",
    "",
    "; One centered line of text: BgImage draws text from its box's left edge, so the box starts where",
    "; the text, measured in its font, is centered.",
    "!macro portableSplashLine TEXT FONT COLOR TOP BOTTOM",
    '  StrCpy $splashText "${TEXT}"',
    "  StrLen $splashX $splashText",
    "  System::Call '*(i 0, i 0) p .s'",
    "  Pop $splashSize",
    "  System::Call 'user32::GetDC(p 0) p .s'",
    "  Pop $splashDc",
    "  System::Call 'gdi32::SelectObject(p $splashDc, p ${FONT}) p .s'",
    "  Pop $splashOldFont",
    "  Push $splashText",
    "  System::Call 'gdi32::GetTextExtentPoint32W(p $splashDc, w s, i $splashX, p $splashSize)'",
    "  System::Call 'gdi32::SelectObject(p $splashDc, p $splashOldFont)'",
    "  System::Call 'user32::ReleaseDC(p 0, p $splashDc)'",
    "  System::Call '*$splashSize(i .s)'",
    "  Pop $splashX",
    "  System::Free $splashSize",
    `  IntOp $splashX ${w} - $splashX`,
    "  IntOp $splashX $splashX / 2",
    "  ${If} $splashX < 0",
    "    StrCpy $splashX 0",
    "  ${EndIf}",
    `  BgImage::AddText "$splashText" \${FONT} \${COLOR} $splashX \${TOP} ${w} \${BOTTOM}`,
    "!macroend",
    "",
    "; The title and one status line, drawn over the bitmap (Clear drops the bitmap too, so it's set again).",
    "!macro portableSplashStatus TEXT",
    "  BgImage::Clear",
    '  BgImage::SetBg "$PLUGINSDIR\\splash.bmp"',
    `  !insertmacro portableSplashLine "${t.text}" $splashTitleFont "${text}" ${t.top} ${t.top + t.height}`,
    `  !insertmacro portableSplashLine "\${TEXT}" $splashStatusFont "${muted}" ${st.top} ${st.top + st.height}`,
    "  BgImage::Redraw",
    "!macroend",
    "",
    "; After BgImage::SetBg: round the window's corners like the app's window (radius.window).",
    "!macro portableSplashShow",
    `  CreateFont $splashTitleFont "${t.font}" ${t.pt} ${t.weight}`,
    `  CreateFont $splashStatusFont "${st.font}" ${st.pt} ${st.weight}`,
    `  !insertmacro portableSplashStatus "${words.starting}"`,
    '  FindWindow $0 "NSISBGImage"',
    "  ${If} $0 <> 0",
    `    System::Call 'gdi32::CreateRoundRectRgn(i 0, i 0, i ${w + 1}, i ${h + 1}, i ${2 * r}, i ${2 * r}) p .r1'`,
    "    System::Call 'user32::SetWindowRgn(p r0, p r1, i 1)'",
    "  ${EndIf}",
    "!macroend",
    "",
    "; Unpacking, with how far along it is (whole percents only, so it redraws at most 100 times).",
    "Function portableSplashProgress",
    "  Pop $R8",
    "  Pop $R9",
    "  System::Int64Op $R8 * 100",
    "  Pop $R8",
    "  ${If} $R9 > 0",
    "    System::Int64Op $R8 / $R9",
    "    Pop $R8",
    "    ${If} $R8 != $splashPercent",
    "      StrCpy $splashPercent $R8",
    `      !insertmacro portableSplashStatus "${words.unpacking} $splashPercent%"`,
    "    ${EndIf}",
    "  ${EndIf}",
    "FunctionEnd",
    "",
    "!macro portableSplashExtract FILE",
    '  StrCpy $splashPercent ""',
    `  !insertmacro portableSplashStatus "${words.unpacking}"`,
    "  GetFunctionAddress $R9 portableSplashProgress",
    '  Nsis7z::ExtractWithCallback "${FILE}" $R9',
    "!macroend",
    "",
    "; Starts the app and keeps the splash until the app's window is shown (its launch log, D-217),",
    "; the app ends (a second copy handing over to the first), or the wait runs out. Then waits for",
    "; the app to end, as ExecWait did, and passes on its exit code.",
    "!macro portableSplashLaunch EXE ARGS",
    `  !insertmacro portableSplashStatus "${words.opening}"`,
    "  ReadEnvStr $6 FOCUS_NOTES_LAUNCH_LOG",
    '  ${If} $6 == ""',
    '    StrCpy $6 "$PLUGINSDIR\\launch.log"',
    "    System::Call 'kernel32::SetEnvironmentVariable(t, t)i (\"FOCUS_NOTES_LAUNCH_LOG\", r6).r5'",
    "  ${EndIf}",
    '  StrCpy $3 `"${EXE}" ${ARGS}`',
    "  System::Alloc 68",
    "  Pop $1",
    "  System::Call '*$1(i 68)'",
    "  System::Alloc 16",
    "  Pop $2",
    "  System::Call 'kernel32::CreateProcessW(p 0, w r3, p 0, p 0, i 0, i 0, p 0, p 0, p r1, p r2) i .r5'",
    "  ${If} $5 == 0",
    "    System::Free $1",
    "    System::Free $2",
    "    BgImage::Destroy",
    '    ExecWait `"${EXE}" ${ARGS}` $0',
    "  ${Else}",
    "    System::Call '*$2(p .r4, p .r5)'",
    "    System::Call 'kernel32::CloseHandle(p r5)'",
    "    System::Free $1",
    "    System::Free $2",
    "    StrCpy $7 0",
    "    ${Do}",
    '      ${If} ${FileExists} "$6"',
    "        ${ExitDo}",
    "      ${EndIf}",
    "      System::Call 'kernel32::WaitForSingleObject(p r4, i 100) i .r5'",
    "      ${If} $5 == 0",
    "        ${ExitDo}",
    "      ${EndIf}",
    "      IntOp $7 $7 + 1",
    `    \${LoopUntil} $7 >= ${waitSteps}`,
    "    BgImage::Destroy",
    "    System::Call 'kernel32::WaitForSingleObject(p r4, i -1)'",
    "    System::Call 'kernel32::GetExitCodeProcess(p r4, *i .r0)'",
    "    System::Call 'kernel32::CloseHandle(p r4)'",
    "  ${EndIf}",
    "  SetErrorLevel $0",
    "!macroend",
    "",
  ];
  // makensis reads an included file as UTF-8 only with a byte order mark.
  return Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(lines.join("\r\n"), "utf8")]);
}

const build = join(import.meta.dirname, "..", "build");
const files = [
  [join(build, "portable-splash.bmp"), bitmap()],
  [join(build, "portable-splash.nsh"), script()],
];
if (process.argv.includes("--check")) {
  const stale = files.filter(([file, data]) => { try { return !readFileSync(file).equals(data); } catch { return true; } });
  if (stale.length) { console.error("The portable splash is out of date. Run node scripts/portable-splash.mjs."); process.exit(1); }
  console.log("Portable splash up to date.");
} else {
  for (const [file, data] of files) writeFileSync(file, data);
  console.log(`Portable splash written: ${files.map(([, d]) => `${d.length} B`).join(", ")}.`);
}

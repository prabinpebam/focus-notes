// The Microsoft Store listing (PKG-12, D-202), written from the product site so the two never
// disagree: site/landing.json gives the description, the short description and the first features,
// site/privacy.md the privacy statement, and store/listing.json the Store's own facts (category,
// keywords, URLs, the age-rating draft, the release notes template, the screenshots' sizes).
//
//   node tools/release/store-listing.mjs           write store/listing.en-US.md
//   node tools/release/store-listing.mjs --check   fail when it's stale or over a Store limit
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const root = join(import.meta.dirname, "..", "..");
const OUT = join(root, "store", "listing.en-US.md");

/** Partner Center's limits for an MSIX app's listing. */
export const LIMITS = { description: 10_000, shortDescription: 1_000, features: 20, feature: 200, keywords: 7, keyword: 40, keywordWords: 21, releaseNotes: 1_500 };

/** The privacy page's words without its front matter, heading or links' Markdown. */
function privacyText(md) {
  const body = md.replace(/^---\n[\s\S]*?\n---\n/, "").replace(/^# .*\n/m, "");
  return body.replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1 ($2)").replace(/\*\*([^*]+)\*\*/g, "$1").trim();
}

/** Every field of the listing, as Partner Center asks for it. */
export function buildListing(landing, privacyMd, store) {
  const lead = `${landing.headline} ${landing.line}`;
  // Sentences that only make sense on the site (a swatch to click, "this site") stay there.
  const storeLine = (t) => (store.siteOnly ?? []).reduce((s, x) => s.replace(x, ""), t).replace(/\s+/g, " ").trim();
  const featureLines = landing.features.map((f) => storeLine(`${f.headline} ${f.line}`));
  const privacy = privacyText(privacyMd);
  const appPrivacy = privacy.split("\n").find((l) => l.startsWith("- The app "))?.slice(2) ?? "";
  const description = [lead, ...featureLines, ...store.about, appPrivacy, landing.closing].join("\n\n");
  const features = [...landing.features.map((f) => storeLine(`${f.eyebrow}: ${f.headline} ${f.line}`)), ...store.features];
  return { description, shortDescription: landing.line, features, keywords: store.keywords, privacy };
}

/** Each way the listing breaks a Partner Center limit. */
export function overLimits(l, releaseNotesTemplate) {
  const p = [];
  if (l.description.length > LIMITS.description) p.push(`The description has ${l.description.length} characters.`);
  if (l.shortDescription.length > LIMITS.shortDescription) p.push("The short description is too long.");
  if (l.features.length > LIMITS.features) p.push(`${l.features.length} features.`);
  for (const f of l.features) if (f.length > LIMITS.feature) p.push(`A feature has ${f.length} characters: ${f}`);
  if (l.keywords.length > LIMITS.keywords) p.push(`${l.keywords.length} keywords.`);
  for (const k of l.keywords) if (k.length > LIMITS.keyword) p.push(`A keyword is too long: ${k}`);
  const words = l.keywords.flatMap((k) => k.split(/\s+/)).length;
  if (words > LIMITS.keywordWords) p.push(`The keywords have ${words} words.`);
  if (releaseNotesTemplate.length > LIMITS.releaseNotes) p.push("The release notes template is too long.");
  return p;
}

const quote = (t) => t.split("\n").map((l) => (l ? `> ${l}` : ">")).join("\n");

/** The listing as one Markdown page, each field ready to paste into Partner Center. */
export function renderListing(landing, privacyMd, store) {
  const l = buildListing(landing, privacyMd, store);
  const a = store.ageRating;
  return `<!-- Generated by tools/release/store-listing.mjs from site/landing.json, site/privacy.md and store/listing.json. Don't edit: edit those, then run it. -->
# Microsoft Store listing: ${store.productName} (${store.language})

**TL;DR:** what to paste into Partner Center → Store listings (${store.language}) and Properties at the first submission. The words come from the product site; draft until ${store.draft}. The steps are in documentations/plan/microsoft-store.md.

## Properties

| Field | Value |
| --- | --- |
| Category | ${store.category} |
| Pricing | ${store.pricing} |
| Markets | ${store.markets} |
| Privacy policy URL | ${store.privacyPolicyUrl} |
| Website | ${store.website} |
| Support contact | ${store.supportUrl} |
| Copyright | ${store.copyright} |
| System requirements | ${store.systemRequirements} |

## Short description

${quote(l.shortDescription)}

## Description

${quote(l.description)}

## Product features

${l.features.map((f) => `- ${f}`).join("\n")}

## Search terms

${l.keywords.map((k) => `- ${k}`).join("\n")}

## Release notes template

${quote(store.releaseNotesTemplate)}

## Notes for certification

${quote(store.certificationNotes)}

## Screenshots

${store.screenshots.required} Scenes: ${store.screenshots.scenes.map((s) => `\`${s}\``).join(", ")}. ${store.screenshots.source}

## Age rating (draft answers)

App type: ${a.appType}.

| Question | Draft answer |
| --- | --- |
${a.answers.map((x) => `| ${x.question} | ${x.answer} |`).join("\n")}

Expected: ${a.expected}.

## Privacy statement (from the privacy page)

${quote(l.privacy)}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const json = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
  const landing = json("site/landing.json"), store = json("store/listing.json");
  const privacy = readFileSync(join(root, "site", "privacy.md"), "utf8").replace(/\r\n/g, "\n");
  const problems = overLimits(buildListing(landing, privacy, store), store.releaseNotesTemplate);
  for (const p of problems) console.error(p);
  const text = renderListing(landing, privacy, store);
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
    if (current !== text) {
      console.error("store/listing.en-US.md is stale: run node tools/release/store-listing.mjs");
      process.exit(1);
    }
    console.log("Store listing up to date.");
  } else {
    writeFileSync(OUT, text);
    console.log("Wrote store/listing.en-US.md.");
  }
  process.exit(problems.length ? 1 : 0);
}
